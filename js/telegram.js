// Optional Telegram bot. Long-polls api.telegram.org while the app is open and a token is set.
// Commands: /note <text> (or any plain text) saves a note into <vault>/Telegram/, /list, /help,
// /sum "topic" asks the local Ollama model for a summary and saves it into <vault>/summaries/.
// The first chat to message the bot is locked in as the owner; every other chat is ignored.
import { writeText, listTree, listNames } from './fs.js';
import { generate, gpuWarning } from './ai.js';
let current = null;
const sleep = ms => new Promise(r => setTimeout(r, ms));
const call = (token, method, body, signal) =>
  fetch(`https://api.telegram.org/bot${token}/${method}`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body), signal }).then(r => r.json());
const flat = (nodes, out = []) => { for (const n of nodes) n.kind === 'dir' ? flat(n.children, out) : out.push(n.path.join('/')); return out; };
const cleanTopic = s => s.trim().replace(/^["'\u201c\u201d\u2018\u2019\u00ab]+|["'\u201c\u201d\u2018\u2019\u00bb]+$/g, '').trim();
const slug = s => s.replace(/#/g, '-sharp').replace(/[\\/:*?"<>|%\x00-\x1f]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 60).replace(/[. ]+$/, '') || 'summary';
const stamp = () => new Date().toISOString().slice(0, 16).replace(/[:T]/g, '-');

export function stop() { current?.abort(); current = null; }

export async function start({ botToken, chatId, ollamaUrl, model, forceGpu }, root, onEvent, onBind) {
  stop();
  botToken = botToken?.trim();
  if (!botToken) return;
  if (!root) { onEvent('Telegram: open a vault folder first.'); return; }
  const ctrl = current = new AbortController();
  const reply = (id, text) => call(botToken, 'sendMessage', { chat_id: id, text }, ctrl.signal);
  let offset = 0;
  onEvent('Telegram bot listening.');
  while (current === ctrl) {
    try {
      const r = await call(botToken, 'getUpdates', { offset, timeout: 25 }, ctrl.signal);
      if (!r.ok) { onEvent('Telegram: ' + r.description); return; }
      for (const u of r.result) {
        offset = u.update_id + 1;
        const m = u.message; if (!m?.text) continue;
        const id = String(m.chat.id);
        if (!chatId) { chatId = id; onBind(id); await reply(id, 'Connected. This chat now controls your vault. Send /help to see commands.'); }
        if (id !== String(chatId)) { await reply(id, 'This bot is private.'); continue; }
        const [rawCmd, ...rest] = m.text.trim().split(/\s+/);
        const cmd = rawCmd.split('@')[0].toLowerCase();
        if (cmd === '/help' || cmd === '/start') await reply(id, 'Send any text or /note <text> to save a note.\n/list shows your 20 newest notes.\n/sum "topic" writes an AI summary into the summaries folder.');
        else if (cmd === '/list') await reply(id, flat(await listTree(root)).slice(-20).join('\n') || 'No notes yet.');
        else if (cmd === '/sum') {
          const topic = cleanTopic(m.text.trim().slice(rawCmd.length));
          if (!topic) { await reply(id, 'Usage: /sum "make summary about loops in C#"'); continue; }
          if (!model) { await reply(id, 'Choose an Ollama model in Settings first.'); continue; }
          await reply(id, `Summarizing "${topic}"... this can take a minute.`);
          try {
            const prompt = `Write a clear, well-structured summary about the following topic in Markdown. Use headings and bullet points, and add short code examples where they help. Reply with the Markdown only.\n\nTopic: ${topic}`;
            const text = (await generate(ollamaUrl, model, prompt, ctrl.signal, forceGpu !== false)).trim();
            if (!text) throw new Error('The model returned an empty answer.');
            const taken = new Set((await listNames(root, ['summaries'])).map(n => n.toLowerCase()));
            let name = `${slug(topic)}.md`;
            if (taken.has(name.toLowerCase())) name = `${slug(topic)}-${stamp()}.md`;
            await writeText(root, ['summaries', name], `# ${topic}\n\n_Summary generated by ${model} on ${stamp().replace(/-(\d\d)-(\d\d)$/, ' $1:$2')}_\n\n${text}\n`);
            await reply(id, `Saved as summaries/${name}\n\n` + (text.length > 3300 ? text.slice(0, 3300) + '\n...(see the full file in your vault)' : text));
            onEvent('Telegram summary saved.', true);
            const warn = await gpuWarning(ollamaUrl, model); if (warn) onEvent('GPU: ' + warn);
          } catch (e) {
            if (current !== ctrl) return;
            await reply(id, 'Summary failed: ' + e.message + '\nIs Ollama running with OLLAMA_ORIGINS set?');
          }
        }
        else {
          const text = cmd === '/note' ? rest.join(' ') : m.text;
          if (!text) { await reply(id, 'Add some text after /note.'); continue; }
          const name = `${stamp()}.md`;
          await writeText(root, ['Telegram', name], text + '\n');
          await reply(id, `Saved as Telegram/${name}`);
          onEvent('Telegram note saved.', true);
        }
      }
    } catch (e) {
      if (current !== ctrl) return;
      onEvent('Telegram error: ' + (e.message || e) + ' (retrying)');
      await sleep(5000);
    }
  }
}